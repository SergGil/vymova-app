// Vymova — scripts/gen-lang-loader.js
// Generates js/features/senses-loader.ts and js/features/grammar-loader.ts:
// mode-utils.ts-style lazy `import()` loader maps for the per-language files
// under data/senses-data/ and data/grammar-data/. Scans those directories
// directly (not a fixed list) — regenerate this (don't hand-edit the loader
// maps) whenever a language's data/{senses,grammar}-data file is added or
// removed, so the new file is picked up automatically — see
// docs/adding-a-language.md.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function langsIn(dataDir, filePrefix) {
  const re = new RegExp(`^${filePrefix}_([a-z]+)\\.ts$`);
  return readdirSync(path.join(ROOT, dataDir))
    .map((f) => f.match(re)?.[1])
    .filter((lang) => lang !== undefined)
    .sort();
}

function genLoader({
  langs,
  outFile,
  dataDir,
  filePrefix,
  constPrefix,
  cacheType,
  valueDesc,
  ensureFnName,
  getFnName,
  cacheVarName,
  extraExports,
  typeImport,
  hasFnName,
}) {
  const loaderLines = langs
    .map((lang) => {
      const constName = `${constPrefix}_${lang.toUpperCase()}`;
      return `  ${/^[a-z]+$/.test(lang) ? lang : `'${lang}'`}: () =>\n    import('../../${dataDir}/${filePrefix}_${lang}.ts').then((m) => m.${constName}),`;
    })
    .join('\n');

  const src = `// Vymova — js/features/${path.basename(outFile)}
// Lazy per-language loader for ${valueDesc}, generated by
// scripts/gen-lang-loader.js (scans ${dataDir}/) — mirrors mode-utils.ts's
// TABLES/LANG_LOADERS pattern for word data. Only the learner's actual
// language(s) get downloaded instead of every language's data eagerly (see
// docs/architecture-assessment.md p.6). Regenerate (don't hand-edit the
// loader map) after adding or removing a ${dataDir}/${filePrefix}_xx.ts file.
${typeImport}

const ${cacheVarName}: Partial<Record<string, ${cacheType}>> = {};
const LOADING: Partial<Record<string, Promise<void>>> = {};

const LOADERS: Partial<Record<string, () => Promise<${cacheType}>>> = {
${loaderLines}
};

/** Returns the cached data for \`lang\`, or undefined if not loaded (yet). */
export function ${getFnName}(lang: string): ${cacheType} | undefined {
  return ${cacheVarName}[lang];
}

/** Loads (and caches) \`lang\`'s data on first call; a no-op if already loaded/loading/unavailable. */
export async function ${ensureFnName}(lang: string): Promise<void> {
  if (${cacheVarName}[lang]) return;
  const loader = LOADERS[lang];
  if (!loader) return;
  if (!LOADING[lang]) {
    LOADING[lang] = loader().then((data) => {
      ${cacheVarName}[lang] = data;
    });
  }
  await LOADING[lang];
}
${
  hasFnName
    ? `
/** True if \`lang\` has data available at all (synchronous — doesn't trigger or wait for a load). */
export function ${hasFnName}(lang: string): boolean {
  return lang in LOADERS;
}
`
    : ''
}
${extraExports ?? ''}`;

  writeFileSync(path.join(ROOT, outFile), src, 'utf8');
  console.log(`Wrote ${outFile} (${langs.length} languages)`);
}

// For synonyms/antonyms/word-families: each language has base data PLUS a
// derived reverse-lookup Map (member word → headword). The source files
// used to persist both (SYNONYM_REVERSE_BY_LANG etc.), but a Map can't
// survive JSON.stringify — so this loader only caches the base data, then
// calls the shared build*Reverse() function (still exported from the
// slimmed data/{synonyms,word-families}.ts) once per language, lazily,
// the first time that language's reverse map is actually asked for.
function genReverseLoader({
  langs,
  outFile,
  dataDir,
  filePrefix,
  constPrefix,
  cacheType,
  valueDesc,
  ensureFnName,
  getDictFnName,
  getReverseFnName,
  cacheVarName,
  reverseCacheVarName,
  typeImport,
  buildReverseImport,
  buildReverseFnName,
  extraExports,
}) {
  const loaderLines = langs
    .map((lang) => {
      const constName = `${constPrefix}_${lang.toUpperCase()}`;
      return `  ${lang}: () =>\n    import('../../${dataDir}/${filePrefix}_${lang}.ts').then((m) => m.${constName}),`;
    })
    .join('\n');

  const src = `// Vymova — js/features/${path.basename(outFile)}
// Lazy per-language loader for ${valueDesc}, generated by
// scripts/gen-lang-loader.js (scans ${dataDir}/) — mirrors mode-utils.ts's
// TABLES/LANG_LOADERS pattern for word data. Only the learner's actual
// language(s) get downloaded instead of every language's data eagerly (see
// docs/architecture-assessment.md p.6). Regenerate (don't hand-edit the
// loader map) after adding or removing a ${dataDir}/${filePrefix}_xx.ts file.
${typeImport}
${buildReverseImport}

const ${cacheVarName}: Partial<Record<string, ${cacheType}>> = {};
const ${reverseCacheVarName}: Partial<Record<string, Map<string, string>>> = {};
const LOADING: Partial<Record<string, Promise<void>>> = {};

const LOADERS: Partial<Record<string, () => Promise<${cacheType}>>> = {
${loaderLines}
};

/** Returns the cached base dict for \`lang\`, or undefined if not loaded (yet). */
export function ${getDictFnName}(lang: string): ${cacheType} | undefined {
  return ${cacheVarName}[lang];
}

/** Returns \`lang\`'s reverse-lookup map (member word → headword), built lazily on first call after the base dict is loaded. Undefined if the base dict itself isn't loaded yet. */
export function ${getReverseFnName}(lang: string): Map<string, string> | undefined {
  const dict = ${cacheVarName}[lang];
  if (!dict) return undefined;
  let rev = ${reverseCacheVarName}[lang];
  if (!rev) {
    rev = ${buildReverseFnName}(dict);
    ${reverseCacheVarName}[lang] = rev;
  }
  return rev;
}

/** Loads (and caches) \`lang\`'s base dict on first call; a no-op if already loaded/loading/unavailable. */
export async function ${ensureFnName}(lang: string): Promise<void> {
  if (${cacheVarName}[lang]) return;
  const loader = LOADERS[lang];
  if (!loader) return;
  if (!LOADING[lang]) {
    LOADING[lang] = loader().then((data) => {
      ${cacheVarName}[lang] = data;
    });
  }
  await LOADING[lang];
}
${extraExports ?? ''}`;

  writeFileSync(path.join(ROOT, outFile), src, 'utf8');
  console.log(`Wrote ${outFile} (${langs.length} languages)`);
}

